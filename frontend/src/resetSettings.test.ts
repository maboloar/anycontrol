import { expect, it, vi } from "vitest";
import type { Profile, MappingInfo } from "./protocol";
vi.mock("./api", () => ({ getMapping: vi.fn(), putMapping: vi.fn(), resetSettings: vi.fn() }));
import { putMapping, resetSettings } from "./api";
import { editDraft, useDraftStore } from "./mappingDraft";
import { resetAllSettings } from "./resetSettings";
import { useApp } from "./store";
it("waits for an in-flight mapping save, clears current settings, and preserves custom jacks and connection", async () => {
  const p: Profile = { version: 1, name: "old", description: "", mappings: [] };
  let finish!: (v: MappingInfo) => void;
  vi.mocked(putMapping).mockReturnValue(new Promise(r => { finish = r; }));
  const result = { mouse: { settings: { mode: "off" } }, mapping: { profile: { ...p, name: "default" }, mode: "observe", warnings: [] } } as never;
  vi.mocked(resetSettings).mockResolvedValue(result);
  localStorage.setItem("anycontrol.customJacks", "keep"); localStorage.setItem("anycontrol.panel.abc.size", "old");
  useApp.setState({ conn: "open", resetBusy: false, idleSeconds: 10, devMode: true });
  editDraft(p, true);
  const layout = vi.fn(), resize = vi.fn();
  window.addEventListener("anycontrol.layout.reset", layout); window.addEventListener("anycontrol.resize.reset", resize);
  const resetting = resetAllSettings();
  expect(resetSettings).not.toHaveBeenCalled();
  editDraft({ ...p, name: "must not restore" }, true);
  finish({ profile: p, mode: "observe", warnings: [] } as unknown as MappingInfo);
  await resetting;
  expect(resetSettings).toHaveBeenCalledTimes(1);
  expect(putMapping).toHaveBeenCalledTimes(1);
  expect(useDraftStore.getState().draft?.name).toBe("default");
  expect(useApp.getState()).toMatchObject({ conn: "open", idleSeconds: 120, devMode: false, resetBusy: false, objects: [] });
  expect(localStorage.getItem("anycontrol.customJacks")).toBe("keep");
  expect(localStorage.getItem("anycontrol.panel.abc.size")).toBeNull();
  expect(layout).toHaveBeenCalledOnce(); expect(resize).toHaveBeenCalledOnce();
  window.removeEventListener("anycontrol.layout.reset", layout); window.removeEventListener("anycontrol.resize.reset", resize);
});
